package math.calculadora.completa.model.calculos.resultados;

public class ResultadoSolucao {
    public double   x;
    public double   y;
    public double   z;
    public boolean  unica;

    public ResultadoSolucao(double x, double y, double z, boolean unica) {
        this.x = x;
        this.y = y;
        this.z = z;
        this.unica = unica;
    }
}
